#!/usr/bin/env python3
"""Pack canonical M123 mono1 demo frames into a deterministic firmware header."""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "public/tab/demo/device/v1"
MANIFEST = BASE / "manifest-M123-2026-11-10.json"
OUT = ROOT / "firmware/tab/include/tab/demo_frames.hpp"
PROFILE = {"width": 800, "height": 480, "stride": 100}
# Fixed hardware demo frame. The browser/static manifest still owns the complete timeline.
SAMPLES = ["10:50"]


def packbits(data: bytes) -> bytes:
    out = bytearray()
    i = 0
    while i < len(data):
        run = 1
        while i + run < len(data) and data[i + run] == data[i] and run < 128:
            run += 1
        if run >= 3:
            out.extend((0x80 | (run - 1), data[i]))
            i += run
            continue
        start = i
        i += run
        while i < len(data) and i - start < 128:
            next_run = 1
            while i + next_run < len(data) and data[i + next_run] == data[i] and next_run < 3:
                next_run += 1
            if next_run >= 3:
                break
            i += min(next_run, 128 - (i - start))
        literal = data[start:i]
        out.append(len(literal) - 1)
        out.extend(literal)
    return bytes(out)


def unpackbits(data: bytes) -> bytes:
    out = bytearray()
    i = 0
    while i < len(data):
        control = data[i]
        i += 1
        count = (control & 0x7f) + 1
        if control & 0x80:
            out.extend([data[i]] * count)
            i += 1
        else:
            out.extend(data[i : i + count])
            i += count
    return bytes(out)


def main() -> None:
    manifest = json.loads(MANIFEST.read_text())
    profile = manifest["display_profile"]
    if (profile["width"], profile["height"], profile["stride_bytes"]) != (800, 480, 100):
        raise SystemExit("M123 demo frame profile is not 800x480 mono1.")

    frames = []
    for time in SAMPLES:
        frame = next((x for x in manifest["frames"] if x["effective_from"].split("T")[1].startswith(time)), None)
        if frame is None:
            raise SystemExit(f"No M123 frame begins at {time}.")
        payload = (ROOT / "public" / frame["path"].lstrip("/")).read_bytes()
        if len(payload) != 48_000 or hashlib.sha256(payload).hexdigest() != frame["sha256"]:
            raise SystemExit(f"Source frame failed length/hash validation at {time}.")
        packed = packbits(payload)
        if unpackbits(packed) != payload:
            raise SystemExit(f"Embedded frame codec round-trip failed at {time}.")
        frames.append((time, frame["frame_revision"], packed))

    lines = [
        "// Generated by scripts/embed_tab_demo_frames.py; do not edit by hand.",
        "#pragma once",
        "#include <Arduino.h>",
        "namespace tab_demo {",
        "constexpr uint16_t WIDTH = 800, HEIGHT = 480, STRIDE = 100;",
        "struct Frame { const char* time; const char* revision; const uint8_t* data; uint32_t size; };",
    ]
    for index, (_, _, packed) in enumerate(frames):
        lines.append(f"static const uint8_t FRAME_{index}[] PROGMEM = {{")
        for offset in range(0, len(packed), 16):
            lines.append("  " + ",".join(f"0x{byte:02x}" for byte in packed[offset : offset + 16]) + ",")
        lines.append("};")
    lines.append("static const Frame FRAMES[] = {")
    for index, (time, revision, packed) in enumerate(frames):
        lines.append(f'  {{"{time}", "{revision}", FRAME_{index}, {len(packed)}}},')
    lines.extend(("};", "constexpr uint8_t FRAME_COUNT = sizeof(FRAMES) / sizeof(FRAMES[0]);", "}  // namespace tab_demo", ""))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"Embedded {len(frames)} verified M123 frames ({sum(len(x[2]) for x in frames)} bytes PackBits).")


if __name__ == "__main__":
    main()
