// Helper to create a rect polygon
function makeRect(x: number, y: number, w: number, h: number): Point2D[] {
  return [
    { x, y },
    { x: x + w, y },
    { x: x + w, y: y + h },
    { x, y: y + h },
  ];
}

// Fixed stable seed generator for continuous reasonable historical trends
function generateSeededHistory(baseVal: number, spread: number, seed: number): number[] {
  const points: number[] = [];
  for (let h = 0; h < 24; h++) {
    const sinFactor = Math.sin((h / 24) * Math.PI * 2 + seed);
    const noise = Math.cos(h * 1.7 + seed * 2) * (spread * 0.2);
    points.push(Number((baseVal + sinFactor * spread + noise).toFixed(1)));
  }
  return points;
}

